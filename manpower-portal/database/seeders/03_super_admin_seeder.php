<?php
/**
 * Seeder: Super Admin Account
 * Database: manpower_portal_db
 * Organization: PRAYAS – The Automation Academy
 */

function seedSuperAdmin(PDO $pdo): void {
    echo "[+] Seeding Super Admin Account..." . PHP_EOL;

    // Check if Super Admin role exists
    $roleStmt = $pdo->prepare("SELECT id FROM `roles` WHERE `name` = 'super_admin' LIMIT 1");
    $roleStmt->execute();
    $roleId = $roleStmt->fetchColumn();

    if (!$roleId) {
        echo "    [ERROR] super_admin role not found. Run roles seeder first." . PHP_EOL;
        return;
    }

    // Check if any active super admin already exists
    $checkStmt = $pdo->prepare("SELECT id, email FROM `users` WHERE `role_id` = :role_id LIMIT 1");
    $checkStmt->execute([':role_id' => $roleId]);
    $existingAdmin = $checkStmt->fetch();

    if ($existingAdmin) {
        echo "    [-] Super Admin account already exists (ID: {$existingAdmin['id']}). Skipping to prevent overwrite." . PHP_EOL;
        return;
    }

    // Retrieve initial credentials from environment or initialize safely
    $adminEmail = getenv('INITIAL_ADMIN_EMAIL') ?: 'admin@prayas-academy.internal';
    $rawPassword = getenv('INITIAL_ADMIN_PASSWORD');
    $isAutoGenerated = false;

    if (empty($rawPassword)) {
        // Generate high-entropy 16-character temporary password
        $rawPassword = bin2hex(random_bytes(8)) . '!P#';
        $isAutoGenerated = true;
    }

    $passwordHash = password_hash($rawPassword, PASSWORD_BCRYPT, ['cost' => 12]);

    $insertStmt = $pdo->prepare("INSERT INTO `users` 
        (`role_id`, `company_id`, `full_name`, `email`, `phone`, `password_hash`, `must_change_password`, `status`) 
        VALUES 
        (:role_id, NULL, :full_name, :email, :phone, :hash, 1, 'Active')");

    $insertStmt->execute([
        ':role_id' => $roleId,
        ':full_name' => 'PRAYAS Master Administrator',
        ':email' => $adminEmail,
        ':phone' => '9999999999',
        ':hash' => $passwordHash
    ]);

    $newAdminId = $pdo->lastInsertId();

    // Log initialization event securely in audit_logs
    $auditStmt = $pdo->prepare("INSERT INTO `audit_logs` (`user_id`, `action`, `ip_address`, `details_json`) 
        VALUES (:uid, 'INITIAL_SUPERADMIN_SEEDED', '127.0.0.1', :details)");
    $auditStmt->execute([
        ':uid' => $newAdminId,
        ':details' => json_encode(['email' => $adminEmail, 'must_change_password' => 1])
    ]);

    echo "    Super Admin account initialized successfully (ID: $newAdminId, Email: $adminEmail)." . PHP_EOL;
    echo "    Security flag 'must_change_password' enabled." . PHP_EOL;

    if ($isAutoGenerated) {
        // Write temporary one-time credentials to local secure setup file
        $setupFilePath = __DIR__ . '/.initial_admin_setup.txt';
        file_put_contents($setupFilePath, 
            "PRAYAS Industry Manpower Requirement Portal - Initial Super Admin Setup\n" .
            "========================================================================\n" .
            "Generated At: " . date('Y-m-d H:i:s') . "\n" .
            "Email:        " . $adminEmail . "\n" .
            "Temp Password:" . $rawPassword . "\n" .
            "Notice:       Super Admin is forced to change this password on initial login.\n" .
            "              Delete this file immediately after initial setup.\n"
        );
        echo "    [SECURITY NOTICE] Temporary one-time credentials written to database/seeders/.initial_admin_setup.txt" . PHP_EOL;
    }
}

